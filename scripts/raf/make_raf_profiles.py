#!/usr/bin/env python3
"""
Build alems run profiles for RAF experiments from their committed configs
(coordinator condition b: profiles are generated, never retyped).

    pilot form (e1_gn100.yaml, e1r2_gn100.yaml): policies, classes, points,
        tasks {late}, early_ordinal -> one clean family, b0_scope all.
    family form (main_gn100.yaml from select_main_tasks.py) -> copied as is,
        b0_scope checks.

Usage (from the engine root):
    python scripts/raf/make_raf_profiles.py --config scripts/raf/e1_gn100.yaml \
        --name raf_e1 --provider <p> --model <m> --out <sandbox>/profiles/raf_e1.yaml
"""

import argparse
import os
import sys

import yaml

HEADER = ("# Generated by scripts/raf/make_raf_profiles.py from %s; do not edit.\n"
          "# Run from the sandbox: alems run profiles/%s\n")


def schedule_from(cfg: dict) -> dict:
    """The schedule section for core/execution/schedule.py."""
    keep = ("seeds", "b0_repetitions", "early_ordinal", "expected_store_suffix")
    out = {k: cfg[k] for k in keep if k in cfg}
    if "families" in cfg:
        out["b0_scope"] = "checks"
        out["families"] = cfg["families"]
        out["tasks"] = cfg["tasks"]
        return out
    out["b0_scope"] = "all"
    out["families"] = {"clean": {"classes": dict(cfg["classes"]),
                                 "options": list(cfg["policies"]),
                                 "points": {p: 1 for p in cfg["points"]}}}
    out["tasks"] = {t: {"stratum": v["stratum"], "families": ["clean"],
                        "targets": {"clean": {"late": dict(v["late"])}}}
                    for t, v in cfg["tasks"].items()}
    return out


def profile_from(cfg: dict, name: str, goal: str, provider: str, model: str,
                 arms: dict = None, study_id: str = "") -> dict:
    val = dict(cfg.get("validity") or {})
    val["classifier"] = "bfcl_raf"
    base = dict(cfg.get("baseline") or {})
    base["remeasure"] = True
    # R6: controller arms join the escalate arm; study_id isolates learning.
    recovery = {"prepare": "bfcl", "arms": dict({"escalate": "escalate_stub"}, **(arms or {}))}
    if study_id:
        recovery["learning"] = {"study_id": study_id}
    return {
        "study": {"name": name, "experiment_type": "failure_injection",
                  "experiment_goal": goal, "workflow_modes": ["agentic"]},
        "providers": [{"name": provider, "model_id": model}],
        "execution": {"save_db": True},
        "quality": {"enabled": True},
        "recovery": recovery,
        "schedule": schedule_from(cfg),
        "isolation": cfg["isolation"],
        "validity": val,
        "baseline": base,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--goal", default="")
    ap.add_argument("--provider", required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--options", default="", help="comma list replacing the config's policies")
    ap.add_argument("--b0", type=int, default=None, help="B0 repetitions per task (0: none)")
    ap.add_argument("--seeds", default="", help="block_order,policy_order replacing the config's")
    ap.add_argument("--families", default="", help="family form: keep only these families")
    ap.add_argument("--tasks", default="", help="keep only these tasks (ids with or without bfcl_)")
    ap.add_argument("--classes", default="", help="pilot form: keep only these classes")
    ap.add_argument("--points", default="", help="pilot form: keep only these points")
    ap.add_argument("--arm", action="append", default=[],
                    help="arm=decider entry point, repeatable (R6: ctrl=ctrl_beta)")
    ap.add_argument("--study-id", default="", help="recovery.learning.study_id (R6)")
    a = ap.parse_args()
    arms = {}
    for spec in a.arm:
        arm, _, dec = spec.partition("=")
        if not arm or not dec:
            sys.exit("--arm needs name=decider, got %r" % spec)
        arms[arm] = dec
    with open(a.config) as fh:
        cfg = yaml.safe_load(fh)
    # Overrides for follow up studies on the same cells (E1b: other options, no B0).
    if a.options:
        cfg["policies"] = [o for o in a.options.split(",") if o]
    if a.b0 is not None:
        cfg["b0_repetitions"] = a.b0
    if a.seeds:
        bo, po = (int(x) for x in a.seeds.split(","))
        cfg["seeds"] = dict(cfg["seeds"], block_order=bo, policy_order=po)
    if a.tasks:
        keep = {t if t.startswith("bfcl_") else "bfcl_" + t for t in a.tasks.split(",") if t}
        missing = keep - set(cfg["tasks"])
        if missing:
            sys.exit("tasks not in the config: %s" % sorted(missing))
        cfg["tasks"] = {t: v for t, v in cfg["tasks"].items() if t in keep}
    if a.classes:
        keep = set(a.classes.split(","))
        cfg["classes"] = {c: p for c, p in cfg["classes"].items() if c in keep}
    if a.points:
        cfg["points"] = [p for p in cfg["points"] if p in a.points.split(",")]
    if a.families and "families" in cfg:
        keep = set(a.families.split(","))
        cfg["families"] = {f: v for f, v in cfg["families"].items() if f in keep}
        tasks = {}
        for t, v in cfg["tasks"].items():
            fams = [f for f in v["families"] if f in keep]
            if fams:
                tasks[t] = dict(v, families=fams,
                                targets={f: x for f, x in v["targets"].items() if f in keep})
        cfg["tasks"] = tasks
    prof = profile_from(cfg, a.name, a.goal or "RAF %s" % a.name, a.provider, a.model,
                        arms=arms, study_id=a.study_id)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(HEADER % (a.config, os.path.basename(a.out)))
        yaml.safe_dump(prof, fh, sort_keys=False, default_flow_style=None, width=120)
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
