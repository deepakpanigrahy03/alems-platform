#!/usr/bin/env python3
"""
Generate a pilot form study config (like scripts/raf/e1_gn100.yaml) for a task
list, with the E1 rule, never by hand.

Rule (e1_gn100.yaml header):
    early ordinal = 2 (second call of the type)
    late ordinal  = round(0.7 x calls of that type), clamped to [3, calls - 1]
    counts        = sweep run 1 (raf_sweep30/sweep_r1.txt), llm and tool
    stratum       = short (llm <= 10), medium (11 to 13), long (14 and more)
isolation, baseline, validity and the store suffix are copied from a template
config (e1_gn100.yaml), so every study uses the same settings.

Check: --tasks raf_e1/e1_tasks.txt with E1's classes reproduces the tasks
block of e1_gn100.yaml exactly (test_make_pilot_config.py).

Usage:
    python scripts/raf/make_pilot_config.py --tasks <tasks.txt> --name raf_e3 \
        --classes json_parse:llm,tool_error:tool --seeds 20261028,20261029 \
        --out scripts/raf/e3_gn100.yaml
"""

import argparse
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SANDBOX = os.path.expanduser("~/sandboxes/raf-mlsys-2027")
LINE = re.compile(r"^(?:r\d+\s+)?(multi_turn_base_\d+)\s+B0\s+.*?llm=(\d+)\s+tool=(\d+)")


def sweep_counts(path: str) -> dict:
    """task id (multi_turn_base_N) -> (llm calls, tool calls) from one sweep file."""
    out = {}
    with open(path) as fh:
        for line in fh:
            m = LINE.match(line.strip())
            if m:
                out[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    return out


def late(n: int) -> int:
    """round(0.7 n) clamped to [3, n - 1] (Python round, as E1)."""
    return max(3, min(n - 1, round(0.7 * n)))


def stratum(llm: int) -> str:
    return "short" if llm <= 10 else ("medium" if llm <= 13 else "long")


def tasks_block(task_ids, counts) -> dict:
    missing = [t for t in task_ids if t not in counts]
    if missing:
        sys.exit("no sweep run 1 counts for: %s" % missing)
    return {"bfcl_" + t: {"stratum": stratum(counts[t][0]),
                          "late": {"llm": late(counts[t][0]), "tool": late(counts[t][1])}}
            for t in task_ids}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tasks", required=True, help="file with one multi_turn_base_N per line")
    ap.add_argument("--name", required=True)
    ap.add_argument("--classes", default="json_parse:llm,tool_error:tool")
    ap.add_argument("--seeds", required=True, help="block_order,policy_order")
    ap.add_argument("--template", default=os.path.join(HERE, "e1_gn100.yaml"))
    ap.add_argument("--sweep", default=os.path.join(SANDBOX, "raf_sweep30", "sweep_r1.txt"))
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    with open(a.tasks) as fh:
        ids = [l.strip() for l in fh if l.strip()]
    with open(a.template) as fh:
        tpl = yaml.safe_load(fh)
    bo, po = (int(x) for x in a.seeds.split(","))
    cfg = {"pilot": a.name, "platform": tpl["platform"],
           "expected_store_suffix": tpl["expected_store_suffix"],
           "seeds": {"block_order": bo, "policy_order": po, "model_seed": 0},
           "policies": list(tpl["policies"]), "b0_repetitions": tpl["b0_repetitions"],
           "classes": dict(c.split(":") for c in a.classes.split(",")),
           "points": ["early", "late"], "early_ordinal": 2,
           "tasks": tasks_block(ids, sweep_counts(a.sweep)),
           "isolation": tpl["isolation"], "baseline": tpl["baseline"], "validity": tpl["validity"]}
    with open(a.out, "w") as fh:
        fh.write("# %s, generated by scripts/raf/make_pilot_config.py from %s; do not edit.\n"
                 "# Rule: early 2; late round(0.7 x calls) clamped to [3, n-1]; counts from %s.\n"
                 % (a.name, os.path.basename(a.tasks), a.sweep))
        yaml.safe_dump(cfg, fh, sort_keys=False, default_flow_style=None, width=120)
    print("wrote", a.out, len(ids), "tasks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
